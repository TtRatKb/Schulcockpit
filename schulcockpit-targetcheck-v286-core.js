/* V0.28.6 – conservative, privacy-safe classifier for Firefox import targets.
 * A freshly bootstrapped empty schoolcockpit is not the same as user work.
 * This helper returns COUNTS ONLY; no names, grades, file contents or pupils.
 */
(function(root){
'use strict';
const watched=['classes','timetable','sequences','lessons','materials','materialCatalog',
 'assessments','backlog','tasks','curricula','competencyCatalogsV200'];
const defaultSettings={schoolYear:'2026/27',weeklyPrintDay:1};
function nonempty(value){
 if(value===null||value===undefined||value===''||value===false||value===0)return false;
 if(Array.isArray(value))return value.length>0;
 if(typeof value==='object')return Object.values(value).some(nonempty);
 return true;
}
function defaultCalendars(value,schoolYear){
 if(value===undefined||value===null)return true;
 if(!value||typeof value!=='object'||Array.isArray(value))return false;
 return Object.entries(value).every(([year,v])=>{
  if(!v||typeof v!=='object'||Array.isArray(v))return false;
  if(Object.keys(v).some(k=>!['customRanges','imports','useCurrentTimetable','createdAt'].includes(k)))return false;
  return Array.isArray(v.customRanges)&&v.customRanges.length===0&&
   Array.isArray(v.imports)&&v.imports.length===0&&
   typeof v.createdAt==='string'&&
   v.useCurrentTimetable===(year===String(schoolYear||'2026/27'));
 });
}
function planning(snapshot){
 if(!snapshot||typeof snapshot!=='object'||Array.isArray(snapshot))
  return {safe:false,reason:'Gespeicherte Planungsdaten haben ein unbekanntes Format.'};
 const counts={};
 for(const key of watched)if(nonempty(snapshot[key])){
  counts[key]=Array.isArray(snapshot[key])?snapshot[key].length:1;
 }
 for(const [key,val]of Object.entries(snapshot)){
  if(watched.includes(key)||key==='settings')continue;
  if(key==='schoolCalendarsV190'){
   if(!defaultCalendars(val,snapshot.settings?.schoolYear))counts.schoolCalendarsV190=1;
   continue;
  }
  if(nonempty(val))counts.additional=(counts.additional||0)+1;
 }
 const settings=snapshot.settings||{};
 if(settings.schoolYear&&settings.schoolYear!==defaultSettings.schoolYear)
  counts.customSettings=(counts.customSettings||0)+1;
 if(settings.weeklyPrintDay!==undefined&&settings.weeklyPrintDay!==1)
  counts.customSettings=(counts.customSettings||0)+1;
 // Selected week/view are generated by initial app boot, not a lesson.
 const safe=Object.keys(counts).length===0;
 return {safe,counts,reason:safe?'Noch keine eigenen Unterrichtsdaten gespeichert.':
   'Im Firefox-Profil wurden bereits Unterrichtsdaten oder Einstellungen gespeichert.'};
}
function safeCatalog(rec,data){
 if(!rec||rec.key!=='__material_catalog_manifest_v171__')return false;
 if(!data||data.kind!=='schulcockpit-material-catalog-local'||
  !Array.isArray(data.entries)||data.entries.length||
  nonempty(data.meta))return false;
 return true;
}
function safeMasterIndex(rec){
 return !!rec&&rec.assessmentId==='__sc_masterclass_v251__:index'&&
  rec.schema==='schulcockpit.private-master-index.v1'&&
  Array.isArray(rec.classes)&&rec.classes.length===0;
}
return root.SC_TARGET_CORE_V286={planning,safeCatalog,safeMasterIndex};
})(typeof globalThis==='object'?globalThis:this);
if(typeof module!=='undefined'&&module.exports)module.exports=globalThis.SC_TARGET_CORE_V286;
