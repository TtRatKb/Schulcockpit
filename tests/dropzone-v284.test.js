const assert=require('node:assert/strict');
const D=require('../schulcockpit-dropzone-v284-core.js');
const file=(name,type='application/octet-stream')=>({name,type});
assert(D.accepted(file('Schulcockpit_Browserumzug_2026-11-06.scbackup'),'.scbackup'));
assert(D.accepted(file('SCHULCOCKPIT.SCBACKUP'),'.scbackup'));
assert(!D.accepted(file('schulcockpit-backup.json','application/json'),'.scbackup'));
assert(D.accepted(file('Arbeitsblatt.pdf','application/pdf'),'.pdf,.png'));
assert(D.accepted(file('scan.png','image/png'),'image/*'));
assert(D.accepted(file('stunden.json','application/json'),'.json,application/json'));
assert(D.accepted(file('wissen.potx'),''));
let r=D.check([file('schulcockpit-backup.json','application/json')],'.scbackup',false);
assert.equal(r.ok,false);assert.match(r.reason,/keine vollständige Browserumzugs-Sicherung/);
r=D.check([file('Schulcockpit_Browserumzug_2026-11-06.scbackup')],'.scbackup',false);
assert.equal(r.ok,true);assert.equal(r.files.length,1);
r=D.check([file('a.pdf','application/pdf'),file('b.pdf','application/pdf')],'.pdf',false);
assert.equal(r.ok,false);assert.match(r.reason,/nur eine Datei/);
r=D.check([file('a.pdf','application/pdf'),file('b.pdf','application/pdf')],'.pdf',true);
assert.equal(r.ok,true);assert.equal(r.files.length,2);
r=D.check([file('a.pdf','application/pdf'),file('b.exe','application/octet-stream')],'.pdf',true);
assert.equal(r.ok,false);assert.match(r.reason,/Dateityp nicht passend/);
assert.equal(D.check([],'.json',true).ok,false);
assert.equal(D.check([file('test.pdf')],'.pdf',false,true).ok,false);
console.log('V0.28.4: encrypted backup type, Finder drop validation, multi-file and directory guard pass');
