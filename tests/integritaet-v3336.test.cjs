const assert=require('node:assert/strict');
const C=require('../schulcockpit-integritaet-v3336-core.js');
const course={id:'r5',subject:'Religion',name:'5a'},year='2026/27';
const catalog=C.catalog(course,year,[{id:'old'}]);
assert.equal(catalog.length,11);
assert.equal(new Set(catalog.map(x=>x.id)).size,11);
assert.ok(catalog.every(x=>x.source==='SchiLF-Protokoll CRU Klasse 5'));
const sequences=[{plan:[{id:'u',competencyIdsV202:[catalog[0].id]}]}];
const evidence=[{id:'e',competencyId:catalog[0].id,status:'done',coverageScope:'partial'}];
const r=C.completeness(catalog,sequences,evidence);
assert.equal(r.rows[0].verified,false);
assert.equal(r.rows[0].partial,true);
assert.equal(r.missingPlan.length,10);
assert.match(C.prompt(course,year,r),/ausschließlich die folgenden Lücken/);
const ev=[{id:'p',lessonId:'cancel',status:'planned'}],lessons=[{id:'cancel',date:'2026-11-30',status:'cancelled'}];
assert.ok(C.reconcile(ev,lessons,()=>year)>0);
assert.equal(ev[0].status,'review_required');
assert.equal(ev[0].schoolYear,year);
assert.equal(ev[0].coverageScope,'partial');
console.log('integritaet-v3336: CRU catalog, completeness, partial coverage and cancellation guard OK');
